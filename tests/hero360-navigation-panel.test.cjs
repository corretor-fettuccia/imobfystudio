const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = path.resolve(__dirname, '..', 'plugins', 'hero360-tour');
const mf = JSON.parse(fs.readFileSync(path.join(base, 'plugin.json'), 'utf8'));
const tpl = fs.readFileSync(path.join(base, 'template.html'), 'utf8');
const js = fs.readFileSync(path.join(base, 'plugin.js'), 'utf8');
const css = fs.readFileSync(path.join(base, 'plugin.css'), 'utf8');
assert.equal(mf.version, '1.2.7');
assert.equal(mf.defaults.showNavigationPanel, false, 'painel de navegação deve iniciar desativado');
const field = mf.fields.find(f => f.key === 'showNavigationPanel');
assert(field && field.type === 'toggle' && field.label === 'Habilitar painel de navegação');
assert.match(tpl, /data-navigation-panel="{{showNavigationPanel}}"/);
assert.match(js, /navigationPanelEnabled=root.dataset.navigationPanel==='true'/);
assert.match(js, /if\(navigationPanelEnabled\)\{\s*const controls=/);
assert.match(js, /zoom-in/);
assert.match(js, /zoom-out/);
assert.match(js, /fullscreen/);
assert.match(css, /data-navigation-panel="false"/);
assert.doesNotMatch(js, /on\(canvas,'wheel'/, 'wheel scroll jamais deve zoomar o tour');
console.log('Hero360Tour: painel opcional inativo por padrão e exportação sincronizada');
