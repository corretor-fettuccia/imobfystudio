const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const JSZip=require(path.join(root,'vendor/jszip.min.js'));
global.JSZip=JSZip;
global.window={JSZip,indexedDB:null,confirm:()=>true,location:{href:'http://localhost/'}};
global.fetch=async url=>{
  const f=path.resolve(root,String(url).split(/[?#]/)[0]);
  if(!f.startsWith(root+path.sep)||!fs.existsSync(f))return{ok:false,status:404};
  const b=fs.readFileSync(f);
  return{ok:true,status:200,headers:{get:()=>null},text:async()=>b.toString(),json:async()=>JSON.parse(b),arrayBuffer:async()=>b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength)};
};
function load(f){vm.runInThisContext(fs.readFileSync(path.join(root,f),'utf8'),{filename:f});}
(async()=>{
  for(const f of ['assets/js/util.js','assets/js/catalog.js','assets/js/plugin-loader.js'])load(f);
  await window.ImobifyPluginLoader.ready;
  for(const f of ['assets/js/typography-system.js','assets/js/renderer.js','assets/js/compiler.js'])load(f);
  const plugin=window.ImobifyCatalog.plugins['benefits-showcase'];
  assert.equal(JSON.parse(fs.readFileSync(path.join(root,'plugins/benefits-showcase/plugin.json'),'utf8')).version,'1.2.1');
  const st=window.ImobifyCatalog.defaultState();
  st.seo.sitemapEnabled='no';
  st.brand.containerWidth=920;
  st.brand.sectionSpace=104;
  st.brand.contentGap=38;
  st.brand.elementGap=24;
  st.brand.componentPadding=30;
  st.brand.bodySize=18;
  st.brand.h2Size=52;
  st.brand.h3Size=23;
  st.brand.textMeasure=51;
  st.brand.typographyWizardEnabled=true;
  st.brand.typographyRoles=window.ImobifyTypeSystem.rolePreset('editorial');
  st.brand.typographyRoles.headline.family='Playfair Display';
  st.brand.typographyRoles.subheadline.family='DM Sans';
  st.brand.typographyRoles.body.family='Montserrat';
  const sec=window.ImobifyCatalog.createSection('benefits-showcase');
  sec.props.align='left';st.sections=[sec];
  let html=plugin.render(sec.props,st,sec.id);
  assert.match(html,/class="site-container"><header class="bs-heading"/);
  assert.match(html,/data-bs-align="left"/);
  const css=fs.readFileSync(path.join(root,'plugins/benefits-showcase/plugin.css'),'utf8');
  assert.match(css,/max-width:min\(100%,var\(--text-measure,66ch\)\)/);
  assert.match(css,/margin:0 0 var\(--content-gap,56px\)/);
  assert.match(css,/--bs-section-pad:var\(--section-space/);
  assert.match(css,/font-size:var\(--body-size,16px\)/);
  assert.match(css,/font-size:clamp\(2\.1rem,5vw,var\(--h2-max,77px\)\)/);
  assert.doesNotMatch(css.slice(css.indexOf('/* v1.2.1')),/padding-inline:/);
  sec.props.backgroundImage='data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///ywAAAAAAQABAAACAUwAOw==';
  html=plugin.render(sec.props,st,sec.id);
  assert.match(html,/class="bs-backdrop"/);
  let out=await window.ImobifyCompiler.compile(st);
  let zip=await JSZip.loadAsync(await out.blob.arrayBuffer());
  const site=await zip.file('index.html').async('text');
  const siteCss=await zip.file('assets/css/site.css').async('text');
  const project=JSON.parse(await zip.file('content/project.json').async('text'));
  assert.equal(project.version,'6.0.83');
  assert.equal(project.brand.containerWidth,920);
  assert.equal(project.brand.sectionSpace,104);
  assert.equal(project.brand.bodySize,18);
  assert.equal(project.sections[0].props.backgroundFixed,true);
  assert.match(site,/data-bs-image="true"/);
  for(const tok of ['--container:920px','--section-space:104px','--content-gap:38px','--body-size:18px','--text-measure:51ch', '--ib-headline-font','--ib-subheadline-font','--ib-body-font','max-width:min(100%,var(--text-measure,66ch))']) assert(siteCss.includes(tok),tok);
  assert(siteCss.includes('var(--section-space,clamp(64px,8vw,112px))'));
  // Centered option must remain available without changing the project's container.
  sec.props.align='center';
  assert.match(plugin.render(sec.props,st,sec.id),/data-bs-align="center"/);
  console.log('Benefits Showcase 1.2.1: margins, typography project tokens, wizard, background and ZIP export OK');
})().catch(e=>{console.error(e);process.exitCode=1});
