const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const base=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(base,p),'utf8');
const catalogJS=read('assets/js/catalog.js');
const scope={window:{ImobifyUtil:{escapeHtml(value){return String(value??'').replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));}}}};
vm.runInNewContext(catalogJS,scope,{filename:'catalog.js'});
const hero=scope.window.ImobifyCatalog.plugins['hero-plus'];
assert.equal(hero.manifest.version,'1.1.0');
const sample={...hero.defaults, image1:'assets/images/hero-placeholder.jpg',image2:'assets/images/gallery-1.jpg'};
const rendered=hero.render(sample,{},'hero-qa');
assert.match(rendered,/class="hp-slide is-active"/);
assert.equal((rendered.match(/class="hp-slide /g)||[]).length,2);
assert.match(rendered,/class="hp-slide-control"/);
assert.match(rendered,/data-slide-transition="crossfade"/);
assert.match(rendered,/--hp-transition-duration:1400ms/);
assert.doesNotMatch(hero.render({...sample,slideAutoplay:false},{},'qa'),/hp-slide-control/);
assert.match(read('plugins/hero-plus/plugin.css'),/\.hp-slide\.is-leaving/);
assert.match(read('plugins/hero-plus/plugin.css'),/margin:0!important/);
assert.match(read('plugins/hero-plus/plugin.css'),/object-fit:cover/);
assert.match(read('plugins/hero-plus/plugin.css'),/text-align:justify/);
assert.match(read('plugins/hero-plus/plugin.css'),/min-height:100dvh/);
assert.match(read('plugins/hero-plus/plugin.js'),/preload\(slides\[next\]\)/);
assert.match(read('plugins/hero-plus/plugin.js'),/current\.classList\.add\('is-leaving'\)/);
const advanced=hero.fields.find(f=>f.key==='slideTransition');
assert.equal(advanced.options.length,5);
assert.equal(hero.fields.find(f=>f.key==='subtitleSize').group,'Texto de apoio');
console.log('Hero Plus 1.1.0 / Imobify 7.1.2: estrutura, controles, cobertura, tipografia e compatibilidade OK');
if(process.argv.includes('--html'))process.stdout.write('RENDERED_HTML:'+Buffer.from(rendered).toString('base64')+'\n');
