const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ROOT=path.join(__dirname,'..');
const JSZip=require(path.join(ROOT,'vendor/jszip.min.js'));
global.window={JSZip,indexedDB:null,confirm:()=>true,location:{href:'http://localhost/'}};
global.JSZip=JSZip;
global.fetch=async u=>{
  const file=path.resolve(ROOT,String(u).split(/[?#]/,1)[0]);
  if(!file.startsWith(ROOT+path.sep)||!fs.existsSync(file))return {ok:false,status:404};
  const b=fs.readFileSync(file);
  return {ok:true,status:200,headers:{get:()=>null},text:async()=>b.toString('utf8'),json:async()=>JSON.parse(b),arrayBuffer:async()=>b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength)};
};
function load(f){vm.runInThisContext(fs.readFileSync(path.join(ROOT,f),'utf8'),{filename:f});}
(async()=>{
  for(const f of ['assets/js/util.js','assets/js/catalog.js','assets/js/icon-library.js','assets/js/plugin-loader.js'])load(f);
  await window.ImobifyPluginLoader.ready;
  for(const f of ['assets/js/typography-system.js','assets/js/renderer.js','assets/js/compiler.js'])load(f);
  const api=window.ImobifyTypeSystem;
  const prior={headline:{size:90,mobile:40}};
  const migrated=api.normalize(prior);
  assert.equal(migrated.headline.size,90);
  assert.equal(migrated.headline.mobile,40);
  assert.equal(migrated.headline.tablet,60,'old settings must receive a derived tablet midpoint');
  const invalid=api.normalize({headline:{tablet:500}});
  assert.equal(invalid.headline.tablet,120,'tablet values should be bounded');
  const brand={typographyWizardEnabled:true,typographyRoles:prior};
  const variables=api.variables(brand);
  assert.match(variables,/--ib-headline-size:90px/);
  assert.match(variables,/@media\(max-width:720px\)/);
  assert.match(variables,/@media\(min-width:321px\) and \(max-width:720px\)/);
  assert.match(variables,/@media\(min-width:721px\) and \(max-width:1439px\)/);
  assert.match(variables,/clamp\(40px,calc\(/);
  assert.match(api.bridgeCss(brand),/ims360-banner-title.*clamp\(24px/);
  const settingsSource=fs.readFileSync(path.join(ROOT,'assets/js/typography-wizard.js'),'utf8');
  for(const name of ['mobile','tablet','desktop'])assert.match(settingsSource,new RegExp('data-tw-device="'+name+'"'));
  assert.match(settingsSource,/data-tw-field="tablet"/);
  const registry=JSON.parse(fs.readFileSync(path.join(ROOT,'plugins/registry.json'),'utf8'));
  assert.equal(registry.corePlugins.length+registry.packages.length,54,'the registered plugin inventory must remain intact');
  const state=window.ImobifyCatalog.defaultState();
  state.seo.sitemapEnabled='no';
  state.brand={...state.brand,...brand};
  state.sections=['hero','highlights','hero360-tour','parallax360-tour','faq'].map(k=>window.ImobifyCatalog.createSection(k));
  state.sections.at(-1).settings.typographyMode='local';
  const before=JSON.stringify(state);
  const output=await window.ImobifyCompiler.compile(state);
  assert.equal(JSON.stringify(state),before,'export may not mutate project settings');
  const zip=await JSZip.loadAsync(await output.blob.arrayBuffer());
  const css=await zip.file('assets/css/site.css').async('string');
  const html=await zip.file('index.html').async('string');
  for(const selector of ['--ib-fluid-reading','--ib-fluid-control','--ib-fluid-card-title','--ib-headline-size'])assert.ok(css.includes(selector),selector);
  assert.match(css,/\[data-plugin="hero360-tour"\]/);
  assert.match(css,/\[data-plugin="parallax360-tour"\]/);
  assert.match(css,/max-width:1199px/);
  assert.match(html,/data-ib-type-mode="local"/);
  assert.ok(zip.file('assets/css/site.css'));
  console.log('Responsive typography 6.0.44 OK: 50-plugin registry, three sizes, fluid CSS, legacy migration, opt-out and exported ZIP.');
})().catch(err=>{console.error(err);process.exitCode=1;});
