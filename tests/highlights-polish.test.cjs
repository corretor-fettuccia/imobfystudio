const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const JSZip=require(path.join(root,'vendor/jszip.min.js'));
global.JSZip=JSZip;
global.window={JSZip,indexedDB:null,confirm:()=>true,location:{href:'http://localhost/'}};
global.fetch=async r=>{
  const f=path.resolve(root,String(r).split(/[?#]/,1)[0]);
  if(!f.startsWith(root+path.sep)||!fs.existsSync(f))return {ok:false,status:404};
  const b=fs.readFileSync(f);
  return {ok:true,status:200,headers:{get:()=>null},text:async()=>b.toString('utf8'),json:async()=>JSON.parse(b),arrayBuffer:async()=>b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength)};
};
function load(file){vm.runInThisContext(fs.readFileSync(path.join(root,file),'utf8'),{filename:file});}
(async()=>{
  for(const f of ['assets/js/util.js','assets/js/catalog.js','assets/js/icon-library.js','assets/js/plugin-loader.js'])load(f);
  await window.ImobifyPluginLoader.ready;
  for(const f of ['assets/js/typography-system.js','assets/js/renderer.js','assets/js/compiler.js'])load(f);
  const catalog=window.ImobifyCatalog;
  const state=catalog.defaultState();
  state.seo.sitemapEnabled='no';
  const section=catalog.createSection('highlights');
  state.sections=[section];
  assert.equal(section.props.layout,'editorial');
  const legacy=catalog.plugins.highlights.render({eyebrow:'BENEFÍCIOS',title:'O projeto',items:'Localização|A 10 minutos do centro\nConforto|Privacidade'},state,section.id);
  assert.match(legacy,/data-highlight-layout="editorial"/);
  assert.equal((legacy.match(/role="listitem"/g)||[]).length,2);
  assert.match(legacy,/id="destaques"/);
  section.props={...section.props,layout:'cards',columns:'4',marker:'dot',subtitle:'Para viver melhor',ctaLabel:'Quero conhecer',ctaHref:'javascript:alert(1)',items:'<img src=x onerror=evil()>|Seguro & bonito\nAmbientes|Amplos | iluminados\nTerraço'};
  const markup=catalog.plugins.highlights.render(section.props,state,section.id);
  assert.match(markup,/data-highlight-layout="cards"/);
  assert.match(markup,/data-highlight-columns="4"/);
  assert.equal((markup.match(/role="listitem"/g)||[]).length,3);
  assert.match(markup,/Seguro &amp; bonito/);
  assert.match(markup,/Amplos \| iluminados/);
  assert.doesNotMatch(markup,/<img src=x/);
  assert.doesNotMatch(markup,/href="javascript:/);
  assert.match(markup,/href="#contato"/);
  const second=catalog.createSection('highlights');state.sections.push(second);
  assert.match(catalog.plugins.highlights.render(second.props,state,second.id),new RegExp('id="destaques-'+second.id.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'"'));
  const css=fs.readFileSync(path.join(root,'plugins/highlights/plugin.css'),'utf8');
  assert.match(css,/data-highlight-layout="compact"/);
  assert.match(css,/@media\(max-width:720px\)/);
  state.brand.typographyWizardEnabled=true;
  state.brand.typographyRoles=window.ImobifyTypeSystem.rolePreset('editorial');
  const out=await window.ImobifyCompiler.compile(state);
  const bundle=await JSZip.loadAsync(await out.blob.arrayBuffer());
  const html=await bundle.file('index.html').async('text');
  const exported=await bundle.file('assets/css/site.css').async('text');
  assert.match(html,/data-highlight-layout="cards"/);
  assert.match(exported,/data-highlight-layout="cards"/);
  assert.match(exported,/--ib-headline-font/);
  assert.match(exported,/--ib-focus-ring/);
  assert.equal((html.match(/id="destaques"/g)||[]).length,1);
  assert.doesNotMatch(html,/href="javascript:/);
  assert.ok(out.blob.size>10000);
  console.log('Destaques 1.1: legacy, variants, escaping, links, unique anchors, responsive and export OK');
})().catch(e=>{console.error(e);process.exitCode=1});
