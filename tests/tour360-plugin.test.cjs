const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const p=(...x)=>path.join(root,...x);
const manifest=JSON.parse(fs.readFileSync(p('plugins/tour360-pro/plugin.json'),'utf8'));
assert.equal(manifest.type,'section');
assert.equal(manifest.id,'tour360-pro');
assert.equal(manifest.version,'3.2.6');
assert.equal(manifest.editor?.mode,'modal');
assert.equal(manifest.editor?.field,'tourConfig');
for(const file of [manifest.editor.template,manifest.editor.style,manifest.editor.script]) assert(fs.existsSync(p('plugins/tour360-pro',file)),`editor file missing: ${file}`);
const editorJs=fs.readFileSync(p('plugins/tour360-pro/editor/app.js'),'utf8');
assert(editorJs.includes('window.ImobifyPluginEditor'));
assert(editorJs.includes('load(raw)'));
assert(editorJs.includes('save()'));
const app=fs.readFileSync(p('assets/js/app.js'),'utf8');
assert(app.includes('data-open-plugin-modal-editor'));
assert(app.includes('pluginModalEditorDialog'));
assert(app.includes('plugin.editorBundle'));
assert(!app.includes("plugins/tour360-pro/editor/index.html?embed=1"),'modal ainda depende de caminho hard-coded');
const loader=fs.readFileSync(p('assets/js/plugin-loader.js'),'utf8');
assert(loader.includes("manifest.editor?.mode === 'modal'"));
assert(loader.includes('editorBundle: record.editor || null'));
assert(loader.includes('html: await read(manifest.editor.template)'));
const compiler=fs.readFileSync(p('assets/js/compiler.js'),'utf8');
assert(compiler.includes("['tour360-pro','hero360-tour','parallax360-tour'].includes(section.type)"));
const registry=fs.readFileSync(p('plugins/registry.json'),'utf8');
assert(registry.includes('plugins/tour360-pro/plugin.json'));
console.log('tour360-plugin.test: OK');

const tpl=fs.readFileSync(p('plugins/tour360-pro/template.html'),'utf8');
const css=fs.readFileSync(p('plugins/tour360-pro/plugin.css'),'utf8');
const runtime=fs.readFileSync(p('plugins/tour360-pro/plugin.js'),'utf8');
assert(tpl.includes('tour360-pro__frame-shell'),'Tour360 deve renderizar em frame interno');
assert(css.includes('width:min(100%,var(--tour360-max))'),'frame deve seguir o padrão responsivo do YouTube');
assert(css.includes('border-radius:var(--tour360-radius'),'frame deve recortar com raio configurável');
assert(runtime.includes('runtimeAsset'),'preview local deve converter Data URL antes do Pannellum');
assert(runtime.includes('URL.createObjectURL'),'preview local deve usar Blob URL');
