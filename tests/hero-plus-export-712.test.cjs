'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),JSZip=require(path.join(root,'vendor/jszip.min.js'));
global.JSZip=JSZip;
global.window={JSZip,indexedDB:null,location:{href:'http://localhost:8765/'}};
global.fetch=async url=>{
 const filename=path.resolve(root,String(url).split(/[?#]/)[0]);
 if(!filename.startsWith(root+path.sep)||!fs.existsSync(filename))return{ok:false,status:404};
 const bytes=fs.readFileSync(filename);
 return{ok:true,headers:{get:()=>null},text:async()=>bytes.toString(),json:async()=>JSON.parse(bytes.toString()),arrayBuffer:async()=>bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength)};
};
const load=filename=>vm.runInThisContext(fs.readFileSync(path.join(root,filename),'utf8'),{filename});
(async()=>{
 for(const file of ['assets/js/util.js','assets/js/catalog.js','assets/js/plugin-loader.js'])load(file);
 await window.ImobifyPluginLoader.ready;
 for(const file of ['assets/js/typography-system.js','assets/js/renderer.js','assets/js/compiler.js'])load(file);
 const state=window.ImobifyCatalog.defaultState();
 const slide=window.ImobifyCatalog.createSection('hero-plus');
 slide.props.image1='assets/images/hero-placeholder.jpg';
 slide.props.image2='assets/images/gallery-1.jpg';
 slide.props.title='Torre única com rooftop completo';
 slide.props.subtitle='Um novo ponto de vista para morar bem, com espaço, infraestrutura e mobilidade.';
 state.sections=[slide];
 const result=await window.ImobifyCompiler.compile(state);
 assert.equal(result.outputState.version,'7.3.3');
 const zip=await JSZip.loadAsync(await result.blob.arrayBuffer());
 const html=await zip.file('index.html').async('text');
 assert.match(html,/data-plugin="hero-plus"/);
 assert.match(html,/hp-slide-control/);
 assert.match(html,/text-align:justify|hp-subtitle/);
 const sources=Object.keys(zip.files);
 const css=(await Promise.all(sources.filter(p=>p.endsWith('.css')).map(p=>zip.file(p).async('text')))).join('\n');
 const js=(await Promise.all(sources.filter(p=>p.endsWith('.js')).map(p=>zip.file(p).async('text')))).join('\n');
 assert.match(css,/\.hp-slide\.is-leaving/);
 assert.match(css,/text-align:justify/);
 assert.match(js,/function setupSlides\(root\)/);
 assert.match(js,/current\.classList\.add\('is-leaving'\)/);
 console.log('Exportação Hero Plus 7.1.2: CSS, JS, controles e tipografia presentes no ZIP público.');
})().catch(error=>{console.error(error);process.exitCode=1;});
