const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ROOT = path.join(__dirname,'..');
const JSZip = require(path.join(ROOT,'vendor/jszip.min.js'));
global.JSZip = JSZip;
global.window = { JSZip, indexedDB:null, confirm:()=>true, location:{href:'http://localhost/'} };
global.fetch = async resource => {
 const file = path.resolve(ROOT,String(resource).split(/[?#]/,1)[0]);
 if(!file.startsWith(ROOT+path.sep)||!fs.existsSync(file))return {ok:false,status:404};
 const buf=fs.readFileSync(file);
 return {ok:true,status:200,headers:{get:()=>null},text:async()=>buf.toString('utf8'),json:async()=>JSON.parse(buf),arrayBuffer:async()=>buf.buffer.slice(buf.byteOffset,buf.byteOffset+buf.byteLength)};
};
function load(name){vm.runInThisContext(fs.readFileSync(path.join(ROOT,name),'utf8'),{filename:name});}
(async()=>{
 for(const p of ['assets/js/util.js','assets/js/catalog.js','assets/js/icon-library.js','assets/js/plugin-loader.js'])load(p);
 await window.ImobifyPluginLoader.ready;
 load('assets/js/typography-system.js');
 load('assets/js/renderer.js');
 load('assets/js/compiler.js');
 const system=window.ImobifyTypeSystem;
 assert.deepEqual(Array.from(system.ROLES),['eyebrow','headline','subheadline','body','cta']);
 const invalid=system.normalize({headline:{size:9999,mobile:1,family:'bad;style',color:'malicious',weight:-1}});
 assert.equal(invalid.headline.size,160);
 assert.equal(invalid.headline.mobile,10);
 assert.equal(invalid.headline.family,'heading');
 assert.equal(invalid.headline.color,'inherit');
 assert.equal(invalid.headline.weight,300);
 const s=window.ImobifyCatalog.defaultState();
 s.seo.sitemapEnabled='no';
 s.sections=[window.ImobifyCatalog.createSection('hero'),window.ImobifyCatalog.createSection('faq')];
 let src=window.ImobifyRenderer.variables(s);
 assert.doesNotMatch(src,/--ib-headline-size/,'No wizard means no changes to legacy typography');
 s.brand.typographyWizardEnabled=true;
 s.brand.typographyRoles=system.rolePreset('impacto');
 s.brand.typographyRoles.headline.color='custom';
 s.brand.typographyRoles.headline.customColor='#123456';
 s.brand.typographyRoles.headline.size=96;
 s.brand.typographyRoles.headline.mobile=41;
 assert.match(window.ImobifyRenderer.variables(s),/--ib-headline-size:96px/);
 assert.match(window.ImobifyRenderer.variables(s),/@media\(max-width:720px\)\{:root\{--ib-eyebrow-size:11px;--ib-headline-size:41px/);
 s.sections[1].settings.typographyMode='local';
 let html=window.ImobifyRenderer.bodyMarkup(s);
 assert.match(html,/data-ib-type-mode="local"/);
 assert.match(html,/data-plugin="hero"/);
 const snapshot=JSON.stringify(s);
 const out=await window.ImobifyCompiler.compile(s);
 assert.equal(JSON.stringify(s),snapshot);
 const zip=await JSZip.loadAsync(await out.blob.arrayBuffer());
 const css=await zip.file('assets/css/site.css').async('string');
 const outputHtml=await zip.file('index.html').async('string');
 assert.match(css,/--ib-headline-size:96px/);
 assert.match(css,/--ib-headline-color:#123456/);
 assert.match(css,/color:var\(--ib-headline-color\)!important/);
 assert.match(css,/--ib-headline-size:41px/);
 assert.match(css,/data-ib-type-mode/);
 assert.match(outputHtml,/data-ib-type-mode="local"/);
 assert.doesNotMatch(outputHtml,/typography-wizard\.js/,'The editor wizard must not leak into landing pages');
 assert.ok(out.blob.size>10000);
 const allRoles=system.bridgeCss(s.brand);
 assert.match(allRoles,/\.ibs-button/);
 assert.match(allRoles,/\.iwfp-button/);
 assert.match(allRoles,/prefers-reduced-motion/);
 console.log('Typography wizard 6.0.40: roles, normalization, backward compatibility, per-section opt-out and exported CSS passed.');
})().catch(e=>{console.error(e);process.exitCode=1});
