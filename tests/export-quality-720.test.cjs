'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const JSZip=require(path.join(root,'vendor/jszip.min.js'));
global.JSZip=JSZip;
global.window={JSZip,indexedDB:null,location:{href:'http://localhost:8000/'}};
global.fetch=async resource=>{
  const pathname=String(resource).split(/[?#]/,1)[0].replace(/^\.\//,'');
  const full=path.resolve(root,pathname);
  if (!full.startsWith(root+path.sep) || !fs.existsSync(full))return {ok:false,status:404};
  const buffer=fs.readFileSync(full);
  return {ok:true,status:200,headers:{get:()=>null},text:async()=>buffer.toString(),json:async()=>JSON.parse(buffer.toString()),arrayBuffer:async()=>buffer.buffer.slice(buffer.byteOffset,buffer.byteOffset+buffer.byteLength)};
};
const load=file=>vm.runInThisContext(fs.readFileSync(path.join(root,file),'utf8'),{filename:file});
(async()=>{
  for(const f of ['assets/js/util.js','assets/js/catalog.js','assets/js/plugin-loader.js'])load(f);
  await window.ImobifyPluginLoader.ready;
  for(const f of ['assets/js/typography-system.js','assets/js/renderer.js','assets/js/compiler.js'])load(f);
  const png='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+pUbcAAAAASUVORK5CYII=';
  const state=window.ImobifyCatalog.defaultState();
  state.projectName='Imagens Empreendimento';
  state.seo.title='Imagens de apartamentos em Canoas';
  state.seo.description='Apartamentos com informações objetivas e fotografias.';
  state.seo.canonical='https://exemplo.com.br/empreendimentos/original/';
  state.seo.lastReviewed='2026-10-28';
  state.seo.sitemapEnabled='yes';
  state.seo.ogImage=png;
  const hero=window.ImobifyCatalog.createSection('hero');
  hero.props.title='Moradias no centro';
  hero.props.image=png;
  const slider=window.ImobifyCatalog.createSection('property-slider');
  slider.props.slides=JSON.stringify([{image:png,title:'Foto da área externa'},{image:'https://cdn.example.org/gallery/photo.webp?v=9&width=800',title:'Foto da fachada'}]);
  const hidden=window.ImobifyCatalog.createSection('hero');hidden.props.image='https://cdn.example.org/private-secret.jpg';hidden.settings.visible=false;
  state.sections=[hero,slider,hidden];
  const output=await window.ImobifyCompiler.compile(state);
  assert.equal(output.outputState.version,'7.3.3');
  const zip=await JSZip.loadAsync(await output.blob.arrayBuffer());
  const sitemap=await zip.file('sitemap.xml').async('text');
  assert.match(sitemap, /xmlns:image="http:\/\/www.google.com\/schemas\/sitemap-image\/1.1"/);
  assert.match(sitemap, /<loc>https:\/\/exemplo.com.br\/empreendimentos\/original\/<\/loc>/);
  assert.match(sitemap, /<image:loc>https:\/\/exemplo.com.br\/empreendimentos\/original\/share.png<\/image:loc>/);
  assert.match(sitemap, /<image:loc>https:\/\/exemplo.com.br\/empreendimentos\/original\/assets\/images\/[^<]+\.(?:png|jpg)<\/image:loc>/);
  assert.match(sitemap, /https:\/\/cdn.example.org\/gallery\/photo.webp\?v=9&amp;width=800/);
  assert.match(sitemap, /<lastmod>2026-10-28<\/lastmod>/);
  assert.doesNotMatch(sitemap, /private-secret|data:image|<changefreq>|<priority>/);
  const urls=[...sitemap.matchAll(/<image:loc>([^<]+)<\/image:loc>/g)].map(x=>x[1]);
  assert.equal(urls.length,new Set(urls).size,'URLs de imagem duplicadas');
  assert.ok(urls.length>=3,'OG, hero e slide remotos devem ser incluídos');
  const report=JSON.parse(await zip.file('content/export-validation.json').async('text'));
  assert.equal(report.version,'7.3.3');assert.equal(report.passed,true);assert.equal(report.images,urls.length);
  assert.ok(report.checks.some(x=>x.id==='webmcp-runtime' && x.ok));
  assert.ok(zip.file('VALIDACAO-EXPORTACAO.txt'));
  assert.match(await zip.file('robots.txt').async('text'),/Sitemap: https:\/\/exemplo.com.br\/empreendimentos\/original\/sitemap.xml/);
  assert.ok(zip.file('llms.txt'));assert.ok(zip.file('llms-full.txt'));assert.ok(zip.file('.well-known/ai-catalog.json'));
  const original=fs.readFileSync(path.join(root,'index.html'),'utf8');
  assert.doesNotMatch(original,/aiAgentOpen|imobifyAiDialog|assets\/js\/ai-agent\.js/);
  const warning=window.ImobifyCatalog.defaultState();warning.sections=[];warning.seo.canonical='';warning.seo.sitemapEnabled='no';
  const noSitemap=await window.ImobifyCompiler.compile(warning);
  assert.equal(noSitemap.exportValidation.passed,true);
  const noSitemapZip=await JSZip.loadAsync(await noSitemap.blob.arrayBuffer());
  assert.equal(noSitemapZip.file('sitemap.xml'),null);
  assert.ok(noSitemap.exportValidation.warnings.length,'Emitir alertas quando não é possível indexar');
  const invalid=window.ImobifyCatalog.defaultState();invalid.seo.canonical='http://example.org/';invalid.seo.sitemapEnabled='yes';
  await assert.rejects(window.ImobifyCompiler.compile(invalid),/URL canônica HTTPS válida/);
  console.log(`Imobify 7.3.3: ${urls.length} imagens indexáveis; sitemap, llms, WebMCP, auditoria e remoção do painel OK`);
})().catch(err=>{console.error(err);process.exitCode=1});
