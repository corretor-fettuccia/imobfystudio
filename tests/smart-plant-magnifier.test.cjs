const fs=require('fs'); const assert=require('assert');
const base='plugins/smart-plant-v1.4.2';
const js=fs.readFileSync(base+'/plugin.js','utf8');
const css=fs.readFileSync(base+'/plugin.css','utf8');
const html=fs.readFileSync(base+'/template.html','utf8');
const manifest=JSON.parse(fs.readFileSync(base+'/plugin.json','utf8'));
assert.equal(manifest.version,'1.4.5');
for (const key of ['magnifierTouchToggle','magnifierClickPosition','magnifierDragPosition','magnifierFollowMouse','magnifierZoom']) assert.ok(Object.prototype.hasOwnProperty.call(manifest.defaults,key), key+' default missing');
assert.equal(manifest.defaults.magnifierZoom,'3');
assert.match(html,/data-magnifier-touch-toggle="{{magnifierTouchToggle}}"/);
assert.match(html,/data-magnifier-click-position="{{magnifierClickPosition}}"/);
assert.match(html,/data-magnifier-drag-position="{{magnifierDragPosition}}"/);
assert.match(html,/data-magnifier-follow-mouse="{{magnifierFollowMouse}}"/);
assert.match(html,/data-magnifier-zoom="{{magnifierZoom}}"/);
assert.match(html,/data-smart-plant-zoom="2"/); assert.match(html,/data-smart-plant-zoom="3"/);
assert.match(css,/width:150px; height:150px/);
assert.match(js,/magnifierTouchToggle/); assert.match(js,/magnifierClickPosition/); assert.match(js,/magnifierDragPosition/); assert.match(js,/magnifierFollowMouse/);
assert.match(js,/zoom = Number\(button\.dataset\.smartPlantZoom\) === 2 \? 2 : 3/);
console.log('Smart Plant 1.4.5 configurable magnifier behavior OK');
