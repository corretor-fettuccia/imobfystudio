'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const plugin=path.join(root,'plugins/hero360-tour');
const manifest=require(path.join(plugin,'plugin.json'));
const runtime=fs.readFileSync(path.join(plugin,'plugin.js'),'utf8');
const editor=fs.readFileSync(path.join(root,'index.html'),'utf8');
const template=fs.readFileSync(path.join(plugin,'template.html'),'utf8');
assert.equal(manifest.version,'1.2.7');
assert.match(runtime,/addEventListener\('deviceorientation',motionRead/);
assert.match(runtime,/addEventListener\('deviceorientationabsolute',motionRead/);
assert.match(runtime,/RelativeOrientationSensor/);
assert.match(runtime,/AbsoluteOrientationSensor/);
assert.match(runtime,/motionPolicyBlocked/);
assert.match(runtime,/Sensores exigem HTTPS/);
assert.match(runtime,/motionState\('connected'/);
assert.match(runtime,/motionState\('blocked'/);
assert.match(runtime,/motionState\('no-data'|,'no-data'/);
assert.match(runtime,/beginCalibration\(yaw,pitch\)/);
assert.match(runtime,/loadScene\(sceneId\);resize\(\);frame=requestAnimationFrame\(tick\)/);
assert.match(editor,/allow="fullscreen; accelerometer; gyroscope; magnetometer"/);
assert.match(template,/data-motion-enabled="\{\{motionEnabled\}\}"/);
new vm.Script(runtime);
console.log('Hero360Tour 1.2.5: Android/iOS, fallback Chromium, status de permissão e preview OK');
