const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.resolve(__dirname, '..', 'plugins', 'parallax');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'plugin.json'), 'utf8'));
const js = fs.readFileSync(path.join(root, 'plugin.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'plugin.css'), 'utf8');
assert.equal(manifest.version, '2.10.3');
assert.match(js, /function isIOSDevice\(\)/);
assert.match(js, /platform === "MacIntel" && Number\(navigator\.maxTouchPoints \|\| 0\) > 1/);
assert.match(js, /const playbackEngine = isIOSDevice\(\) \? "ios" : "default"/);
assert.match(js, /function runIOSForwardTransition/);
assert.match(js, /function runPlaybackEngine/);
assert.match(js, /if \(playbackEngine === "ios"\) runIOSForwardTransition/);
assert.match(js, /const finalSeekTolerance = playbackEngine === "ios" \? 0\.12 : 0\.006/);
const iosStart = js.indexOf('function runIOSForwardTransition');
const routerStart = js.indexOf('function runPlaybackEngine');
assert(iosStart > 0 && routerStart > iosStart);
const iosBody = js.slice(iosStart, routerStart);
assert.match(iosBody, /video\.play\(\)/);
assert.match(iosBody, /requestVideoFrameCallback/);
assert.doesNotMatch(iosBody, /video\.currentTime\s*=\s*desired/);
assert.match(iosBody, /\["waiting","stalled","seeking","seeked","playing","canplay"\]/);
assert.match(css, /svp-engine-ios\.svp-cinematic-running/);
assert.match(css, /backdrop-filter: none !important/);
console.log('Parallax dual engine iOS behavior OK');
